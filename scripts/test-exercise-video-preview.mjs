import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import vm from 'node:vm';
import { build } from 'esbuild';
import { JSDOM } from 'jsdom';
import React, { act } from 'react';
import { createRoot } from 'react-dom/client';
const dom = new JSDOM('<div id="root"></div>', { url:'https://example.test' });
globalThis.window = dom.window;
globalThis.document = dom.window.document;
globalThis.IS_REACT_ACT_ENVIRONMENT = true;
dom.window.HTMLDialogElement.prototype.showModal = function () { this.open = true; };
dom.window.HTMLDialogElement.prototype.close = function () { this.open = false; this.dispatchEvent(new dom.window.Event('close')); };
const { outputFiles } = await build({entryPoints:[new URL('../ExerciseVideoPreview.jsx', import.meta.url).pathname],bundle:true,write:false,format:'cjs',platform:'node',packages:'external',jsx:'automatic'});
const module = {exports:{}};
vm.runInNewContext(outputFiles[0].text, {module,exports:module.exports,require:createRequire(import.meta.url), URL});
const Preview = module.exports.default;
const root = createRoot(document.getElementById('root'));
const playback = {url:'https://example.test/own.mp4',source:'own',clip:{start:3,end:9}};
await act(() => root.render(React.createElement(React.StrictMode,null,React.createElement(Preview,{name:'Knee Tucks',playback}))));
const trigger = document.querySelector('button');
assert.equal(trigger.getAttribute('aria-label'),'Video ansehen: Knee Tucks');
assert.equal(document.querySelector('video').getAttribute('src'),'https://example.test/own.mp4#t=3');
assert(!document.querySelector('dialog'));
await act(() => trigger.click());
assert(document.querySelector('dialog').open);
assert(document.querySelector('dialog video').controls);
await act(() => document.querySelector('[aria-label="Video schließen"]').click());
assert(!document.querySelector('dialog'));
assert.equal(document.activeElement,trigger);
await act(() => trigger.click());
await act(() => document.querySelector('dialog').close());
assert(!document.querySelector('dialog'), 'native Escape/close event removes player');
await act(() => root.render(React.createElement(Preview,{name:'Missing',playback:{url:''}})));
assert(!document.querySelector('button'));
await act(() => root.unmount());
console.log('Video previews: uploaded thumbnail, clip start, modal controls, native close, focus restoration and missing video passed.');
